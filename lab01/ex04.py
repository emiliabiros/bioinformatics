def translate_rna_to_protein(s):
    protein = ""

    for i in range(0, len(s) - 2, 3):
        codon = s[i : i + 3]
        amino_acid = codon_table.get(codon)

        if amino_acid == "stop":
            break
        if amino_acid:
            protein += amino_acid

    print(protein)


def main():
    s = input()
    translate_rna_to_protein(s)


