def parse_fasta(lines):
    sequences = []
    current_seq = []
    for line in lines:
        line = line.strip()
        if not line:
            continue
        if line.startswith(">"):
            if current_seq:
                sequences.append("".join(current_seq))
                current_seq = []
        else:
            current_seq.append(line)
    if current_seq:
        sequences.append("".join(current_seq))
    return sequences


def global_alignment_affine(s, t, open_pen=11, ext_pen=1):
    n = len(s)
    m = len(t)

    NEG_INF = float("-inf")

    M = [[NEG_INF] * (m + 1) for _ in range(n + 1)]
    X = [[NEG_INF] * (m + 1) for _ in range(n + 1)]
    Y = [[NEG_INF] * (m + 1) for _ in range(n + 1)]

    trace_M = [[None] * (m + 1) for _ in range(n + 1)]
    trace_X = [[None] * (m + 1) for _ in range(n + 1)]
    trace_Y = [[None] * (m + 1) for _ in range(n + 1)]

    M[0][0] = 0

    for i in range(1, n + 1):
        X[i][0] = -open_pen - (i - 1) * ext_pen
        trace_X[i][0] = "X" if i > 1 else "M"

    for j in range(1, m + 1):
        Y[0][j] = -open_pen - (j - 1) * ext_pen
        trace_Y[0][j] = "Y" if j > 1 else "M"

    for i in range(1, n + 1):
        for j in range(1, m + 1):

            candidates = [
                (M[i - 1][j] - open_pen, "M"),
                (X[i - 1][j] - ext_pen, "X"),
                (Y[i - 1][j] - open_pen, "Y")
            ]

            X[i][j], trace_X[i][j] = max(candidates, key=lambda x: x[0])

            candidates = [
                (M[i][j - 1] - open_pen, "M"),
                (Y[i][j - 1] - ext_pen, "Y"),
                (X[i][j - 1] - open_pen, "X")
            ]

            Y[i][j], trace_Y[i][j] = max(candidates, key=lambda x: x[0])

            score = BLOSUM62[s[i - 1]][t[j - 1]]

            candidates = [
                (M[i - 1][j - 1], "M"),
                (X[i - 1][j - 1], "X"),
                (Y[i - 1][j - 1], "Y")
            ]

            best, prev = max(candidates, key=lambda x: x[0])

            M[i][j] = best + score
            trace_M[i][j] = prev

    candidates = [
        (M[n][m], "M"),
        (X[n][m], "X"),
        (Y[n][m], "Y")
    ]

    max_score, state = max(candidates, key=lambda x: x[0])

    i, j = n, m

    align_s = []
    align_t = []

    while i > 0 or j > 0:

        if state == "M":
            prev = trace_M[i][j]

            align_s.append(s[i - 1])
            align_t.append(t[j - 1])

            i -= 1
            j -= 1

            state = prev

        elif state == "X":
            prev = trace_X[i][j]

            align_s.append(s[i - 1])
            align_t.append("-")

            i -= 1

            state = prev

        elif state == "Y":
            prev = trace_Y[i][j]

            align_s.append("-")
            align_t.append(t[j - 1])

            j -= 1

            state = prev

    aligned_s = "".join(reversed(align_s))
    aligned_t = "".join(reversed(align_t))

    return max_score, aligned_s, aligned_t


