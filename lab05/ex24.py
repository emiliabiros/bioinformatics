def parse_fasta(lines):
    sequences = []
    current_seq = []

    for line in lines:
        line = line.strip()
        if not line:
            continue
        if line.startswith(">"):
            if current_seq:
                sequences.append("".join(current_seq))
                current_seq = []
        else:
            current_seq.append(line)

    if current_seq:
        sequences.append("".join(current_seq))

    return sequences


def local_alignment(s, t):
    n = len(s)
    m = len(t)
    NEG = -10**9

    M = [[0] * (m + 1) for _ in range(n + 1)]
    X = [[NEG] * (m + 1) for _ in range(n + 1)]
    Y = [[NEG] * (m + 1) for _ in range(n + 1)]

    trace_m = [[0] * (m + 1) for _ in range(n + 1)]
    trace_x = [[0] * (m + 1) for _ in range(n + 1)]
    trace_y = [[0] * (m + 1) for _ in range(n + 1)]

    best_score = 0
    best_i = best_j = best_state = 0

    for i in range(1, n + 1):
        for j in range(1, m + 1):
            sub_score = BLOSUM62[s[i-1]][t[j-1]]

            candidates = [0, M[i-1][j-1] + sub_score, X[i-1][j-1] + sub_score, Y[i-1][j-1] + sub_score]
            k = max(range(4), key=lambda x: candidates[x])
            M[i][j] = candidates[k]
            trace_m[i][j] = k if k > 0 else 0
            if candidates[k] > 0 and k == 0:
                trace_m[i][j] = 0

            if M[i][j] == 0:
                trace_m[i][j] = 0
            elif k == 0:
                trace_m[i][j] = 4
            else:
                trace_m[i][j] = k

            candidates_x = [M[i-1][j] - 11, X[i-1][j] - 1]
            if candidates_x[0] >= candidates_x[1]:
                X[i][j] = candidates_x[0]
                trace_x[i][j] = 1
            else:
                X[i][j] = candidates_x[1]
                trace_x[i][j] = 2

            candidates_y = [M[i][j-1] - 11, Y[i][j-1] - 1]
            if candidates_y[0] >= candidates_y[1]:
                Y[i][j] = candidates_y[0]
                trace_y[i][j] = 1
            else:
                Y[i][j] = candidates_y[1]
                trace_y[i][j] = 3

            if M[i][j] > best_score:
                best_score = M[i][j]
                best_i, best_j, best_state = i, j, 1

    aligned_s = []
    aligned_t = []

    i, j, state = best_i, best_j, best_state

    while state != 0:
        if state == 1:
            prev_state = trace_m[i][j]
            if prev_state == 0:
                break
            aligned_s.append(s[i-1])
            aligned_t.append(t[j-1])
            i -= 1
            j -= 1
            if prev_state == 4:
                break
            state = prev_state

        elif state == 2:
            prev_state = trace_x[i][j]
            aligned_s.append(s[i-1])
            i -= 1
            state = prev_state

        else:
            prev_state = trace_y[i][j]
            aligned_t.append(t[j-1])
            j -= 1
            state = prev_state

    return (
        best_score,
        "".join(reversed(aligned_s)),
        "".join(reversed(aligned_t))
    )


def main():
    lines = []

    while True:
        try:
            line = input()
            if not line.strip():
                if lines:
                    break
                continue
            lines.append(line.strip())
        except EOFError:
            break

    s, t = parse_fasta(lines)
    score, aligned_s, aligned_t = local_alignment(s, t)

    print(score)
    print(aligned_s)
    print(aligned_t)


